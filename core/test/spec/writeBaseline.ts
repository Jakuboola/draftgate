/**
 * `bun run spec:baseline` -- rewrite `baseline.ts` from what differs now, and print what moved. For
 * a PR that closes a gap, or a rebase conflict in `baseline.ts` (take either side, then run this).
 * Read what it prints: it records a row going up as readily as one going down.
 */

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { measure } from './measure';
import { FUZZ_FAMILIES } from './measure';
import { FUZZ_BASELINES, moved, rows } from './ratchet';

const m = measure();
const quote = (x: string) => `'${x.replace(/[\\']/g, (c) => `\\${c}`)}'`;
const list = (xs: readonly (number | string)[]) => `[${xs.map((x) => (typeof x === 'string' ? quote(x) : String(x))).join(', ')}]`;

const out = `/**
 * The ratchet: every input the converter reads differently from CommonMark 0.31.2 +
 * GFM TODAY, outside the deliberate differences in \`normalise.ts\`. May only shrink.
 *
 * GENERATED by \`bun run spec:baseline\` -- do not hand-edit, and read what it prints before
 * committing. One line per spec section and per block of fuzz bodies, so two PRs closing gaps in
 * different sections merge without a conflict. On a conflict here, take either side and re-run it.
 *
 * \`bun run spec:report <section | number>\` shows both readings of an entry.
 */

/** Spec section -> the example numbers in it that read differently. */
export const SPEC_BASELINE: Readonly<Record<string, readonly number[]>> = {
${[...m.spec].map(([s, xs]) => `  ${quote(s)}: ${list(xs)},`).join('\n')}
};

/** GFM 0.29 table examples (\`inputs.ts\` \`GFM_TABLE_EXAMPLES\`) that read differently. */
export const GFM_BASELINE: readonly number[] = ${list(m.gfm)};

/** Repo fixtures that read differently. */
export const FIXTURE_BASELINE: readonly string[] = ${list(m.fixtures)};

${FUZZ_FAMILIES.map(
  ({ key }) => `/** ${FUZZ_BASELINES[key].doc} */
export const ${FUZZ_BASELINES[key].exported}: Readonly<Record<number, readonly number[]>> = {
${[...m.fuzz[key]].map(([b, xs]) => `  ${b}: ${list(xs)},`).join('\n')}
};`
).join('\n\n')}
`;
writeFileSync(join(import.meta.dir, 'baseline.ts'), out);

const report = rows(m).flatMap((r) => moved(r)?.line ?? []);
console.log(report.length ? report.join('\n') : 'Nothing moved.');
