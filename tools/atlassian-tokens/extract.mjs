/**
 * Extract Atlassian's light and dark token values for the variables `jira.css` uses.
 *
 * Dev instrument: not a dependency, not in the plugin tree. `@atlaskit/tokens` is installed here,
 * git-ignored, and its published values are emitted as CSS custom properties; the CSS is what ships.
 * There is no `@atlaskit` in the repo's `package.json` or the bundle.
 *
 * Hand-copied values cannot be re-derived and give no dark column. One value is cross-checked
 * against an independent measurement: `color.text.subtlest` = #6B6E76 is what the jira-ruler
 * measures for Jira's line numbers.
 *
 * Naming: Atlassian's CSS variable for a token is `--ds-` + the token path, dropping a leading
 * `color` or `elevation` group and every `[default]` segment. `color.link.[default]` -> `--ds-link`;
 * `elevation.surface.[default].[default]` -> `--ds-surface`.
 *
 * Run: `bun run tokens:jira` (needs `npm install` in this directory first).
 */

import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const require_ = createRequire(join(HERE, 'noop.cjs'));

const RAW = '@atlaskit/tokens/dist/cjs/artifacts/tokens-raw/atlassian-';

/** The variables `jira.css` declares that are genuinely colour tokens. Fonts, radius and the two
 *  Jira-specific surfaces are not in the token set and stay hand-authored. */
const WANTED = [
  '--ds-text', '--ds-text-subtlest', '--ds-link', '--ds-surface', '--ds-border',
  '--ds-background-neutral',
  '--ds-text-accent-blue', '--ds-text-accent-green', '--ds-text-accent-teal',
  '--ds-text-accent-purple', '--ds-text-accent-red', '--ds-text-accent-yellow',
  // Chrome, not body. These drive draftgate's OWN controls -- the primary button, the neutral
  // button's hover, the compose frame -- restyled into Jira's idiom. `text-inverse` is the one
  // nobody would get right by hand: it is #FFFFFF in light and #1F1F21 in DARK, because the dark
  // brand button is a light blue that needs dark text on it.
  '--ds-background-brand-bold', '--ds-background-brand-bold-hovered', '--ds-text-inverse',
  '--ds-background-neutral-subtle-hovered', '--ds-background-input', '--ds-border-input',
  /*
   * The ground JSM renders an INTERNAL NOTE on, and the one token here whose use was measured
   * rather than assumed from its name.
   *
   * In a real JSM ticket, both themes, with a public comment directly above it for contrast, the
   * internal note's band samples `#FEF7C8` in light and `#332E1B` in dark, and
   * `color.background.accent.yellow.subtlest` is exactly those two values -- so a screenshot says
   * WHICH token, and the token supplies the value.
   */
  '--ds-background-accent-yellow-subtlest',
  /*
   * The mention chip. `@atlaskit/mention`'s own `mention-style.js` names these two for
   * `MentionType.DEFAULT` -- the state a mention of SOMEONE ELSE renders in, which is the only one
   * draftgate can honestly draw. See `jira.css`'s mention rule.
   */
  '--ds-text-subtle', '--ds-background-neutral-hovered',
  /*
   * Table cells, named by `@atlaskit/renderer` 144.1.1's own table rules: a header cell is
   * `accent.gray.subtlest` and every cell border is `accent.gray.subtler` -- OPAQUE, unlike the
   * translucent `--ds-border`. The two draw the same pixels on white (#DDDEE1) and different ones on
   * a dark surface.
   */
  '--ds-background-accent-gray-subtlest', '--ds-background-accent-gray-subtler',
];

const toVar = (name) => {
  const parts = name.split('.').filter((p) => p !== '[default]');
  if (parts[0] === 'color' || parts[0] === 'elevation') parts.shift();
  return '--ds-' + parts.join('-');
};

function load(theme) {
  let tokens;
  try {
    tokens = require_(RAW + theme + '.js').default;
  } catch (e) {
    console.error(
      `extract: cannot load @atlaskit/tokens (${e.message}).\n` +
        `Run \`npm install\` in ${HERE} first. It is git-ignored.`
    );
    process.exit(1);
  }
  const out = {};
  for (const t of tokens) {
    const v = toVar(t.name);
    if (WANTED.includes(v) && out[v] === undefined) out[v] = t.value;
  }
  return out;
}

const light = load('light');
const dark = load('dark');

const missing = WANTED.filter((v) => light[v] === undefined || dark[v] === undefined);
if (missing.length) {
  console.error(`extract: no token resolved for ${missing.join(', ')} -- the naming rule has drifted.`);
  process.exit(1);
}

// Committed as evidence: `surface/harness/tokens.test.ts` checks `jira.css`'s palettes against it.
writeFileSync(join(HERE, 'tokens.json'), JSON.stringify({ light, dark }, null, 1) + '\n');

const block = (values) => WANTED.map((v) => `  ${v}: ${values[v]};`).join('\n');

console.log(`/* GENERATED by tools/atlassian-tokens/extract.mjs -- @atlaskit/tokens ${
  require_('@atlaskit/tokens/package.json').version
}. Do not hand-edit. */`);
console.log(`[data-destination="jira"] {\n${block(light)}\n}`);
console.log(`[data-destination="jira"][data-theme="dark"] {\n${block(dark)}\n}`);
